
public class Cafe
{
    private int _totalSales;
    private int _orderTimes;

    public int TotalSales
    {
        get
        {
            return _totalSales;
        }

        set
        {
            _totalSales = value;
        }
    }

    public int OrderTimes
    {
        get
        {
            return _orderTimes;
        }

        set
        {
            _orderTimes = value;
        }
    }
}